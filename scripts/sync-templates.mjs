#!/usr/bin/env node
/**
 * sync-templates.mjs — keep the built-in templates and their embedded
 * snapshot in step (conformance-spec §19.5, §19.9).
 *
 * `templates/<name>/` is the source of truth for a built-in template: a
 * complete project — `site/` beside `README.md`, `DEPLOY.md` (and the blog's
 * `scripts/gen.mjs`, and a `unify.yaml` with the lines the template needs
 * live — `keep:` under `template:` in every built-in, §19.11) — laid out
 * exactly as `unify init`
 * lays one out, which is also what makes each directory usable as a git
 * template on its own (`unify init https://github.com/fwdslsh/unify/templates/blog`).
 *
 * `unify init <name>` does not read that directory: a compiled single-file
 * executable has no sibling directory to read, and `unify init` works offline
 * on purpose. So this script embeds the directories as data —
 * `src/templates/snapshot.js`, a generated module reached by static import —
 * and the suite fails when the two disagree (tests/unit/templates.test.js).
 * Edit the files under templates/, run this, commit both.
 *
 * It also regenerates the `unify.yaml` of each template that ships one from
 * the option registry (§18: the file lists every saveable option, so it cannot
 * fall behind the CLI), keeping whichever lines the template has live (the
 * `template:` block with its `keep:` list in every built-in, the docs
 * template's `catalog: true`, the blog's `generate: scripts/gen.mjs`).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { configTemplate, parseConfig } from "../src/cli/options.js";
import { readTemplateTree } from "../src/cli/template-source.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TEMPLATES_DIR = join(ROOT, "templates");
export const SNAPSHOT_PATH = join(ROOT, "src", "templates", "snapshot.js");

/**
 * The live (uncommented) entries of a scaffolded unify.yaml, in the shape
 * `configTemplate` takes — read by the CLI's own reader, so the `template:`
 * block comes back as it is written.
 * @param {string} yaml
 * @returns {ReturnType<typeof parseConfig>}
 */
export function liveEntries(yaml) {
  return parseConfig(yaml);
}

/**
 * Text stays text; anything that is not valid UTF-8, or holds a NUL, is bytes.
 * @param {Buffer} buf
 * @returns {string|{base64: string}}
 */
function encode(buf) {
  const text = buf.toString("utf8");
  return !buf.includes(0) && Buffer.from(text, "utf8").equals(buf) ? text : { base64: buf.toString("base64") };
}

/**
 * Every template under `dir`, read exactly as `unify init <directory>` reads
 * one (template-source.js's reader), values encoded for the snapshot.
 * @param {string} [dir]
 * @returns {Record<string, {files: Record<string, string|{base64: string}>, rootFiles: Record<string, string|{base64: string}>}>}
 */
export function buildSnapshot(dir = TEMPLATES_DIR) {
  const snapshot = {};
  for (const name of readdirSync(dir).sort()) {
    const { files, rootFiles } = readTemplateTree(join(dir, name), name);
    const encodeAll = (map) => Object.fromEntries(Object.keys(map).sort().map((k) => [k, encode(Buffer.from(map[k]))]));
    snapshot[name] = { files: encodeAll(files), rootFiles: encodeAll(rootFiles) };
  }
  return snapshot;
}

/** @param {ReturnType<typeof buildSnapshot>} snapshot @returns {string} the module's source */
export function renderSnapshot(snapshot) {
  return [
    "// GENERATED by scripts/sync-templates.mjs from templates/ — do not edit.",
    "// Edit the files under templates/<name>/ and run: bun scripts/sync-templates.mjs",
    "// A string is a UTF-8 file; {base64} is a binary one (§19.5). Nothing here reads the filesystem.",
    `export const SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};`,
    "",
  ].join("\n");
}

/** Rewrite the unify.yaml of every template that ships one from the registry, keeping its live lines, then write the snapshot. */
export function sync() {
  for (const name of readdirSync(TEMPLATES_DIR)) {
    const path = join(TEMPLATES_DIR, name, "unify.yaml");
    if (existsSync(path)) writeFileSync(path, configTemplate(liveEntries(readFileSync(path, "utf8"))));
  }
  writeFileSync(SNAPSHOT_PATH, renderSnapshot(buildSnapshot()));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === (await import("node:fs")).realpathSync(process.argv[1])) {
  sync();
  process.stdout.write(`wrote ${SNAPSHOT_PATH}\n`);
}
